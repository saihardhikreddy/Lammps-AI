"""
LAMMPS Input Script Generator

Generates parameterized LAMMPS scripts for uniaxial tensile deformation
and thermal equilibration simulations.
"""

from typing import Dict, Any


def generate_tensile_script(params: Dict[str, Any]) -> str:
    """Generate a clean LAMMPS input script for tensile loading."""
    temp = params.get("temperature", 300.0)
    strain_rate = params.get("strain_rate", 0.01)
    timestep = params.get("timestep", 0.001)
    run_steps = params.get("run_steps", 25000)
    potential_file = params.get("potential_file", "Cu01.eam.alloy")
    element = params.get("element", "Cu")

    script = f"""# -------------------------------------------------------------
# Parameterized LAMMPS Tensile Deformation Input Script
# Auto-generated by LAMMPS-AI workflow generator
# -------------------------------------------------------------

# 1. INITIALIZATION
units           metal
dimension       3
boundary        p p p
atom_style      atomic

# 2. ATOM DEFINITION & LATTICE
lattice         fcc 3.615
region          simbox block 0 10 0 10 0 20
create_box      1 simbox
create_atoms    1 box

# 3. INTERATOMIC POTENTIAL
pair_style      eam/alloy
pair_coeff      * * {potential_file} {element}

# 4. EQUILIBRATION (NPT at {temp} K)
velocity        all create {temp} 12345 mom yes rot yes
fix             1 all npt temp {temp} {temp} 0.1 x 0.0 0.0 1.0 y 0.0 0.0 1.0 z 0.0 0.0 1.0
timestep        {timestep}
thermo          500
run             5000
unfix           1

# 5. UNIAXIAL TENSILE DEFORMATION (Z-axis)
fix             1 all npt temp {temp} {temp} 0.1 x 0.0 0.0 1.0 y 0.0 0.0 1.0
fix             2 all deform 1 z erate {strain_rate} units box remap x

variable        strain equal "(lz - v_L0)/v_L0"
variable        pzz equal "-pzz/10000"

# 6. OUTPUT LOGGING
dump            1 all custom 1000 dump_tensile.lammpstrj id type x y z
fix             def_out all print 100 "${{strain}} ${{pzz}}" file stress_strain.txt screen no

# 7. RUN EXECUTION
run             {run_steps}

print "TENSILE DEFORMATION SIMULATION COMPLETED."
"""
    return script


if __name__ == "__main__":
    test_script = generate_tensile_script({"temperature": 300.0, "strain_rate": 0.01})
    print("Sample generated LAMMPS script preview:")
